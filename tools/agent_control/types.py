    QA_PASSED = "QA_PASSED"
    FOUNDER_APPROVED_FOR_INTEGRATION = "FOUNDER_APPROVED_FOR_INTEGRATION"
    INTEGRATED = "INTEGRATED"
    PUSHED = "PUSHED"
