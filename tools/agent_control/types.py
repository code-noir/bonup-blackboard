"""Closed vocabularies shared by the versioned control records."""
from enum import StrEnum


class ValidationError(ValueError):
    """Invalid control data. Messages identify fields, never echo supplied values."""


class AuthorityError(ValidationError):
    """The supplied trusted context does not authorize an operation."""


